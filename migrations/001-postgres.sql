CREATE SCHEMA money_private;
REVOKE ALL ON SCHEMA money_private FROM PUBLIC;
CREATE TABLE money_private.applications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 80),
  email TEXT NOT NULL CHECK (char_length(email) BETWEEN 3 AND 254),
  preference TEXT NOT NULL CHECK (preference IN ('平日の日中','平日の夕方以降','土日祝','相談して決めたい')),
  message TEXT NOT NULL DEFAULT '' CHECK (char_length(message) <= 1000),
  created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE money_private.admin_login_attempts (
  client TEXT PRIMARY KEY,
  failures INTEGER NOT NULL CHECK (failures BETWEEN 0 AND 5),
  locked_until BIGINT NOT NULL CHECK (locked_until >= 0),
  updated_at BIGINT NOT NULL CHECK (updated_at >= 0)
);
CREATE INDEX admin_login_attempts_updated_at ON money_private.admin_login_attempts(updated_at);
